// v49 — offline, original-color PDF. Eight user-approved frames, in screen order.
// Captures the currently visible circuit and analysis in the same order as the page.
(() => {
  'use strict';

  const A4_LONG = 841.89;
  const A4_SHORT = 595.28;
  const MARGIN = 20;
  const MAX_SCALE = 1.5;

  function bytes(str) { return new TextEncoder().encode(str); }
  function concat(parts) {
    let length = 0;
    for (const part of parts) length += part.length;
    const result = new Uint8Array(length);
    let offset = 0;
    for (const part of parts) { result.set(part, offset); offset += part.length; }
    return result;
  }
  function jpgBytes(dataUrl) {
    const binary = atob(dataUrl.split(',')[1]);
    const output = new Uint8Array(binary.length);
    for (let i = 0; i < binary.length; i++) output[i] = binary.charCodeAt(i);
    return output;
  }
  // Assemble an image-only, standards-compliant PDF using embedded JPEG pages.
  function makePdf(jpegPages) {
    const objects = [null];
    const add = value => { objects.push(value); return objects.length - 1; };
    const catalog = add(null), pages = add(null);
    const pageRefs = [];
    for (const {data, width, height, landscape:pageLandscape} of jpegPages) {
      const img = jpgBytes(data);
      const image = add(concat([
        bytes(`<< /Type /XObject /Subtype /Image /Width ${width} /Height ${height} /ColorSpace /DeviceRGB /BitsPerComponent 8 /Filter /DCTDecode /Length ${img.length} >>\nstream\n`),
        img, bytes('\nendstream')
      ]));
      const landscape = typeof pageLandscape === "boolean" ? pageLandscape : width >= height;
      const PAGE_W = landscape ? A4_LONG : A4_SHORT;
      const PAGE_H = landscape ? A4_SHORT : A4_LONG;
      const cw = PAGE_W - 2 * MARGIN;
      const ch = PAGE_H - 2 * MARGIN;
      const scale = Math.min(cw / width, ch / height);
      const drawnWidth = width * scale;
      const effectiveHeight = height * scale;
      const x = (PAGE_W - drawnWidth) / 2;
      const y = (PAGE_H - effectiveHeight) / 2;
      const body = bytes(`q\n${drawnWidth.toFixed(3)} 0 0 ${effectiveHeight.toFixed(3)} ${x.toFixed(3)} ${y.toFixed(3)} cm\n/Im0 Do\nQ\n`);
      const contents = add(concat([bytes(`<< /Length ${body.length} >>\nstream\n`), body, bytes('endstream')]));
      const page = add(bytes(`<< /Type /Page /Parent ${pages} 0 R /MediaBox [0 0 ${PAGE_W} ${PAGE_H}] /Resources << /XObject << /Im0 ${image} 0 R >> >> /Contents ${contents} 0 R >>`));
      pageRefs.push(page);
    }
    objects[catalog] = bytes(`<< /Type /Catalog /Pages ${pages} 0 R >>`);
    objects[pages] = bytes(`<< /Type /Pages /Count ${pageRefs.length} /Kids [${pageRefs.map(id => `${id} 0 R`).join(' ')}] >>`);
    const pieces = [bytes('%PDF-1.4\n%Generated by Digital Logic Analyzer\n')];
    let pos = pieces[0].length;
    const offsets = [0];
    for (let i = 1; i < objects.length; i++) {
      offsets[i] = pos;
      const obj = concat([bytes(`${i} 0 obj\n`), objects[i], bytes('\nendobj\n')]);
      pieces.push(obj);
      pos += obj.length;
    }
    const xref = pos;
    let table = `xref\n0 ${objects.length}\n0000000000 65535 f \n`;
    for (let i = 1; i < objects.length; i++) table += `${String(offsets[i]).padStart(10, '0')} 00000 n \n`;
    pieces.push(bytes(table + `trailer\n<< /Size ${objects.length} /Root ${catalog} 0 R >>\nstartxref\n${xref}\n%%EOF`));
    return new Blob(pieces, {type: 'application/pdf'});
  }

  // Capture ORIGINAL computed styles, not the monochrome print-only clone.
  // The existing print workflow is deliberately left unchanged.
  const SVG_NS = 'http://www.w3.org/2000/svg';
  const XHTML_NS = 'http://www.w3.org/1999/xhtml';

  function inlineStyles(source, copy) {
    const originalNodes = [source, ...source.querySelectorAll('*')];
    const copiedNodes = [copy, ...copy.querySelectorAll('*')];
    for (let i=0; i<originalNodes.length; i++) {
      const original = originalNodes[i];
      const element = copiedNodes[i];
      if (!element) continue;
      const css = window.getComputedStyle(original);
      const declarations=[];
      for (let j=0; j<css.length; j++) {
        const key=css[j];
        // Browser coordinates, effects and CSS variables are taken as displayed.
        // Avoid external SVG references in generated snapshots.
        let value=css.getPropertyValue(key);
        if ((key==='background-image' || key==='mask-image') && /url\(/i.test(value)) value='none';
        declarations.push(`${key}:${value}${css.getPropertyPriority(key)?'!important':''}`);
      }
      element.setAttribute('style',declarations.join(';'));
      if (element instanceof HTMLInputElement) {
        element.setAttribute('value',original.value);
        if(original.checked) element.setAttribute('checked','checked');
      }
      if(element instanceof HTMLTextAreaElement) element.textContent=original.value;
    }
  }

  async function embedImages(root) {
    const pictures=[...root.querySelectorAll('img')];
    await Promise.all(pictures.map(async img=>{
      const original=img.getAttribute('src');
      if(!original || original.startsWith('data:')) return;
      try {
        const url=new URL(original,document.baseURI).href;
        const file=await fetch(url).then(res=>{if(!res.ok)throw Error('Image unavailable');return res.blob();});
        const inline=await new Promise((resolve,reject)=>{
          const reader=new FileReader();reader.onload=()=>resolve(reader.result);
          reader.onerror=reject;reader.readAsDataURL(file);
        });
        img.setAttribute('src',inline);
      } catch(err) {
        console.warn('PDF: could not embed an image:',original,err);
        img.removeAttribute('src');
      }
    }));
  }

  async function capturePage(def) {
    const original=document.querySelector(def.selector);
    if(!original || !original.getClientRects().length) throw Error(`Section is not visible: ${def.title}`);
    const rect=original.getBoundingClientRect();
    const width=Math.max(250,Math.ceil(rect.width),original.scrollWidth);
    const height=Math.max(120,Math.ceil(rect.height),original.scrollHeight);
    // Clone the LIVE, colored frame directly; do not use the print-only
    // .dla-report-page because its !important monochrome rules override colors.
    const copy=original.cloneNode(true);
    inlineStyles(original,copy);
    copy.removeAttribute('id');
    for(const el of copy.querySelectorAll('[id]'))el.removeAttribute('id');
    for(const el of copy.querySelectorAll('script,iframe'))el.remove();
    // Don't capture active print-hover glows, if any.
    copy.classList.remove('dla-print-hover');
    for(const el of copy.querySelectorAll('.dla-print-hover'))el.classList.remove('dla-print-hover');
    await embedImages(copy);
    copy.style.width=width+'px';copy.style.height=height+'px';
    copy.style.maxWidth='none';copy.style.maxHeight='none';
    copy.style.minWidth='0';copy.style.margin='0';
    copy.style.transform='none';copy.style.transformOrigin='top left';
    copy.style.position='relative';copy.style.left='0';copy.style.top='0';
    copy.style.overflow='hidden';
    // All export pages use original colors, including background and SVG strokes.
    const wrap=document.createElement('div');
    wrap.setAttribute('xmlns',XHTML_NS);
    wrap.setAttribute('style',`width:${width}px;height:${height}px;overflow:hidden;position:relative;background:#08152b;`);
    wrap.append(copy);
    return {width,height,markup:new XMLSerializer().serializeToString(wrap)};
  }

  async function rasterizePage(snapshot) {
    const maxDimension=2200;
    const scale=Math.min(2, maxDimension/snapshot.width,maxDimension/snapshot.height);
    const result=document.createElement('canvas');
    result.width=Math.max(1,Math.round(snapshot.width*scale));
    result.height=Math.max(1,Math.round(snapshot.height*scale));
    const context=result.getContext('2d',{alpha:false,willReadFrequently:true});
    if(!context)throw Error('Canvas rendering is unavailable.');
    context.fillStyle='#ffffff';context.fillRect(0,0,result.width,result.height);
    const svg=`<svg xmlns="${SVG_NS}" width="${snapshot.width}" height="${snapshot.height}" viewBox="0 0 ${snapshot.width} ${snapshot.height}"><foreignObject x="0" y="0" width="100%" height="100%">${snapshot.markup}</foreignObject></svg>`;
    const data='data:image/svg+xml;charset=utf-8,'+encodeURIComponent(svg);
    const image=new Image();
    await new Promise((resolve,reject)=>{
      image.onload=resolve;
      image.onerror=()=>reject(new Error('Browser could not render the colored PDF frame.'));
      image.src=data;
    });
    context.drawImage(image,0,0,result.width,result.height);
    let dataUrl;
    try {dataUrl=result.toDataURL('image/jpeg',0.94);}
    catch(e){throw Error('Browser blocked canvas export; unable to create a valid PDF: '+e.message);}
    // Detect previously observed *blank* pages before allowing a download.
    // The outer frame always has a dark original background, so an empty
    // image is not a valid capture of this application.
    const sample=context.getImageData(0,0,result.width,result.height).data;
    let dark=0;
    for(let i=0;i<sample.length;i+=Math.max(4,4*Math.floor(sample.length/60000/4))){
      if(sample[i]<100 && sample[i+1]<120 && sample[i+2]<160)dark++;
    }
    if(dark<12)throw Error('PDF page rendered empty. Export cancelled instead of downloading blank pages.');
    return {data:dataUrl,width:result.width,height:result.height};
  }

  async function exportColoredPdf() {
    const button = document.getElementById('exportBtn');
    if (button?.disabled) return;
    const caption = button?.textContent;
    if (button) { button.disabled=true;button.textContent='Exporting…'; }
    try {
      const definitions=window.dlaReportFrames;
      if (!Array.isArray(definitions) || definitions.length!==8) throw new Error('Eight report frames are required.');
      const pages=[];
      for (const def of definitions) {
        const snapshot=await capturePage(def);
        const jpg=await rasterizePage(snapshot);
        pages.push({...jpg,landscape:def.landscape});
      }
      const output = makePdf(pages);
      const url = URL.createObjectURL(output);
      const link = document.createElement('a');
      link.href=url;
      link.download='DigitalLogicAnalyzer.pdf';
      document.body.appendChild(link);link.click();link.remove();
      setTimeout(()=>URL.revokeObjectURL(url),30000);
    } catch (error) {
      console.error('PDF export failed',error);
      alert(`Unable to export PDF: ${error.message}`);
    } finally {
      if (button) {button.disabled=false;button.textContent=caption;}
    }
  }
  window.dlaExportColoredPdf = exportColoredPdf;
})();
